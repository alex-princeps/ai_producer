def build_slot_3_facts(fact_status: FactStatusType, missing_hint: str | None = None) -> str:
    if fact_status == "ZERO":
        return (
            "[СТАТУС ФАКТУРЫ: ZERO - ПУСТЫЕ ВВОДНЫЕ]\n"
            "Клиент попросил текст с нуля, но не дал ни черновика, ни конкретных цифр/кейсов/метода.\n"
            "КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО выдумывать за клиента фальшивые кейсы, цены, города и технологии. "
            "В блоке «СТАЛО:» дай жёсткий структурный каркас поста с наглядными плейсхолдерами в квадратных скобках "
            "[укажите ваш реальный кейс / метод / чек] (без обратных кавычек!) и потребуй прислать живую фактуру."
        )
    if fact_status == "PARTIAL":
        hint_part = f" (не хватает детали: {missing_hint})" if missing_hint else ""
        return (
            f"[СТАТУС ФАКТУРЫ: PARTIAL - НЕХВАТКА КОНКРЕТНОЙ ДЕТАЛИ ПРОДУКТА{hint_part}]\n"
            "Внутри готового текста «СТАЛО:» опирайся только на названные клиентом факты, а недостающий механизм защиты/фичу/цифру "
            "ОБЯЗАТЕЛЬНО оберни в квадратные скобки [укажите ваш реальный механизм: например, ...] (без обратных кавычек!). "
            "СТРОГИЙ ЗАПРЕТ: никогда не пиши от лица клиента неподтверждённые юридические/финансовые обещания вроде «гарантия сохранности капитала/бюджета»."
        )
    return (
        "[СТАТУС ФАКТУРЫ: FULL]\n"
        "Фактуры достаточно для чистовика: пиши готовый к публикации текст без лишних заглушек [...]. "
        "При этом строго запрещено приписывать продукту клиента несуществующие технические функции, выдуманные кейсы/цифры или юридические гарантии сохранности бюджета/результата, которых клиент не называл."
    )


