def _write_md(items: list[dict]):
    lines = [
        "# Золотой фонд воскресной B2B-рубрики («Вскрытие кассы» и «Хроники Франкенштейна»)",
        "",
        "> **Назначение:** Воскресная рубрика для прогрева когорт **S2 (дорогостоящие эксперты)** и **S3 (фаундеры агентств, клиник, EdTech и B2B-компаний)** под чек **150 000 – 250 000 ₽** (разработка кастомного ИИ-двойника) и старшие тарифы бота.",
        "> **Как редактировать:**",
        "> - Вы можете свободно править формулировки любых тем или добавлять новые прямо в этом файле.",
        "> - `[В ОЧЕРЕДИ]` — тема стоит в очереди на публикацию по воскресеньям.",
        "> - `[ОПУБЛИКОВАНО]` — тема уже выходила в канале.",
        "> - В скобках после статуса указывается подрубрика: `(Вскрытие кассы)` или `(Хроники Франкенштейна)`.",
        "",
        "---",
        "",
    ]
    for item in items:
        status = "ОПУБЛИКОВАНО" if item.get("used") else "В ОЧЕРЕДИ"
        tid = item.get("id")
        kind = item.get("kind") or "Вскрытие кассы"
        lines.append(f"## Тема #{tid} [{status}] ({kind})")
        lines.append((item.get("prompt") or "").strip())
        lines.append("")
    try:
        with open(B2B_MD_FILE, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
    except Exception as e:
        logger.error(f"Ошибка записи {B2B_MD_FILE}: {e}")


def sync_from_md_if_needed(json_items: list[dict]) -> list[dict]:
    if not os.path.exists(B2B_MD_FILE):
        _write_md(json_items)
        return json_items
    try:
        if os.path.exists(B2B_JSON_FILE) and os.path.getmtime(B2B_MD_FILE) <= os.path.getmtime(B2B_JSON_FILE):
            return json_items
        with open(B2B_MD_FILE, "r", encoding="utf-8") as f:
            md_text = f.read()
        matches = list(_MD_HEADER_RE.finditer(md_text))
        if not matches:
            return json_items
        by_id = {int(i.get("id", 0)): i for i in json_items}
        synced = []
        for idx, m in enumerate(matches):
            tid = int(m.group(1))
            status_raw = m.group(2).strip().upper()
            kind_raw = (m.group(3) or "Вскрытие кассы").strip()
            start = m.end()
            end = matches[idx + 1].start() if idx + 1 < len(matches) else len(md_text)
            p_text = md_text[start:end].strip()
            if not p_text:
                continue
            prev = by_id.get(tid, {})
            is_used = status_raw != "В ОЧЕРЕДИ"
            synced.append({
                "id": tid,
                "kind": kind_raw,
                "title": p_text[:80],
                "prompt": p_text,
                "used": is_used,
                "used_at": prev.get("used_at") if is_used else None,
            })
        with open(B2B_JSON_FILE, "w", encoding="utf-8") as f:
            json.dump(synced, f, ensure_ascii=False, indent=2)
        logger.info(f"🔄 [B2B Vault] Синхронизировано {len(synced)} тем из Золотой_фонд_B2B_и_Франкенштейн.md")
        return synced
    except Exception as e:
        logger.error(f"Ошибка синхронизации из {B2B_MD_FILE}: {e}")
        return json_items


def load_b2b_vault() -> list[dict]:
    items = []
    if os.path.exists(B2B_JSON_FILE):
        try:
            with open(B2B_JSON_FILE, "r", encoding="utf-8") as f:
                items = json.load(f)
        except Exception as e:
            logger.error(f"Ошибка загрузки {B2B_JSON_FILE}: {e}")
    if not items:
        items = [
            {
                "id": t["id"],
                "kind": t["kind"],
                "title": t["prompt"][:80],
                "prompt": t["prompt"],
                "used": False,
                "used_at": None,
            }
            for t in DEFAULT_B2B_TOPICS
        ]
        save_b2b_vault(items)
        return items
    return sync_from_md_if_needed(items)


def save_b2b_vault(items: list[dict]):
    try:
        with open(B2B_JSON_FILE, "w", encoding="utf-8") as f:
            json.dump(items, f, ensure_ascii=False, indent=2)
        _write_md(items)
    except Exception as e:
        logger.error(f"Ошибка сохранения {B2B_JSON_FILE}: {e}")


def get_next_b2b_topic() -> dict | None:
    vault = load_b2b_vault()
    for item in vault:
        if not item.get("used"):
            item["used"] = True
            item["used_at"] = datetime.now().isoformat()
            save_b2b_vault(vault)
            logger.info(f"🎯 [B2B Vault] Взята тема #{item.get('id')} ({item.get('kind')}): {item.get('title')[:60]}...")
            return item
    logger.warning("⚠️ [B2B Vault] Все темы использованы!")
    return None


def peek_next_b2b_topic() -> dict | None:
    vault = load_b2b_vault()
    for item in vault:
        if not item.get("used"):
            return item
    return None


def count_b2b_stats() -> tuple[int, int]:
    vault = load_b2b_vault()
    return len(vault), sum(1 for i in vault if not i.get("used"))
