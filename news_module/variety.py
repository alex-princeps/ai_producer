# Совет в конце был в 30 постах из 30 и превращал продюсера в бизнес-коуча. Теперь примерно в половине постов
# его нет: в коротких форматах чаще, в разборах реже.
NO_TAKEAWAY_FORMATS = {"sting", "bet", "memory", "observation", "doubt"}
NO_TAKEAWAY_PROB = {"short": 0.7, "long": 0.35}


def _texts(history: list[dict], n: int) -> list[str]:
    return [h.get("text") or "" for h in history[-n:]]


def usage(history: list[dict]) -> dict[str, int]:
    """Сколько из последних постов (по окну мотива) содержат каждый мотив."""
    return {k: sum(1 for t in _texts(history, MOTIFS[k][1]) if _COMPILED[k].search(t)) for k in MOTIFS}


def banned_motifs(history: list[dict]) -> list[str]:
    """Мотивы, которые в следующем посте запрещены: в окне последних постов их уже было больше лимита."""
    used = usage(history)
    return [k for k in MOTIFS if used[k] > MOTIFS[k][2]]


ALWAYS = [k for k in MOTIFS if MOTIFS[k][2] < 0]  # запрещено всегда, в промпте это отдельные правила


def prompt_block(banned: list[str]) -> str:
    banned = [k for k in banned if k not in ALWAYS]
    if not banned:
        return ""
    items = "\n".join(f"- {MOTIFS[k][3]}" for k in banned)
    return (
        "[НЕ ПОВТОРЯЙСЯ: это было в твоих недавних постах, в этом посте этого нет совсем]\n" + items
    )


def motifs_in(text: str) -> list[str]:
    """Мотивы, которые уже есть в тексте (для добивки: не повторять слова своего же поста)."""
    return [k for k in MOTIFS if MOTIFS[k][2] >= 0 and _COMPILED[k].search(text or "")]


def has_private(text: str) -> bool:
    """Семья или здоровье автора: в предложении от первого лица или в его старых формулах о матери."""
    text = text or ""
    if OWN_MOTHER_RE.search(text) or HEALTH_ALWAYS_RE.search(text):
        return True
    for sentence in re.split(r"(?<=[.!?…])\s+|\n+", text):
        if FIRST_PERSON_RE.search(sentence) and (FAMILY_RE.search(sentence) or HEALTH_RE.search(sentence)):
            return True
    return False


def violations(text: str, banned: list[str]) -> list[str]:
    """Проблемы для переписывания: запрещённые сейчас мотивы и всегда запрещённое личное."""
    keys = list(dict.fromkeys(list(banned) + ALWAYS))
    problems = [(f"{MOTIFS[k][3]}: убери" if k in ALWAYS else f"повтор из недавних постов: {MOTIFS[k][3]}, убери или скажи иначе")
                for k in keys if _COMPILED[k].search(text or "")]
    if has_private(text):
        problems.append(PRIVATE_FIX)
    first = re.split(r"(?<=[.!?…])\s", (text or "").strip(), maxsplit=1)[0]
    if SELF_OPENING_RE.search(first):
        problems.append(SELF_OPENING_FIX)
    return problems


def pick_takeaway_style(history: list[dict], rng, fmt_id: str = "") -> tuple[str, str | None]:
    """Форма вывода для читателя или ("none", None): в этом посте совета нет."""
    p_none = NO_TAKEAWAY_PROB["short" if fmt_id in NO_TAKEAWAY_FORMATS else "long"]
    if rng.random() < p_none:
        return "none", None
    recent = {h.get("takeaway_style") for h in history[-2:]}
    pool = [s for s in TAKEAWAY_STYLES if s[0] not in recent] or TAKEAWAY_STYLES
    return rng.choice(pool)
