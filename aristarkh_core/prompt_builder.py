    explicit_char_limit: int = 0
    missing_fact_hint: str = ""
    core_pain_one_liner: str = ""
    needs_search: bool = False
    search_query: str = ""

    @property
    def fact_sufficiency(self) -> FactStatusType:
        return self.fact_status

    @fact_sufficiency.setter
    def fact_sufficiency(self, val: FactStatusType) -> None:
        self.fact_status = val

    @classmethod
    def model_validate(cls, data: dict) -> "RouteDecision":
        valid_keys = {
            "intent_type",
            "register",
            "genre",
            "fact_status",
            "is_revision_of_prev",
            "has_bio_request",
            "explicit_char_limit",
            "missing_fact_hint",
            "core_pain_one_liner",
            "needs_search",
            "search_query",
        }
        filtered = {k: v for k, v in (data or {}).items() if k in valid_keys and v is not None}
        if "fact_sufficiency" in (data or {}) and "fact_status" not in filtered:
            filtered["fact_status"] = data["fact_sufficiency"]
        return cls(**filtered)

    def model_dump_json(self) -> str:
        return json.dumps(asdict(self), ensure_ascii=False)


