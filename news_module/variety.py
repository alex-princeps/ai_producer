"""
Разнообразие постов канала: живой автор не повторяет себя из поста в пост.

Аудит 25.10.2026 показал, что модель зацикливается:
- исторические параллели (Версаль, двор Екатерины, Рим, девятнадцатый век) почти в каждом посте;
- кредо цитируется дословно («зритель - вечный подросток», «уйдёт к холодильнику», «не прощает фальшь»);
- одни и те же словечки («разводка», «прайм», «перебивка», «вылизанный»);
- финал почти всегда «Если у вас салон, юрфирма или стройка...»;
- «в девяностые / в нулевые мы...» и «стою у окна, за окном хмарь» через пост.

Здесь по истории последних постов решается, что в следующем посте запрещено, а после генерации
проверяется, нарушен ли запрет. Нарушение отправляет пост на один проход переписывания (_polish).

Отдельно и всегда, без оглядки на историю, запрещено личное, чего такой человек не стал бы писать
в публичном канале: семья (мама, жёны, дети, внуки, дед), здоровье (таблетки, врачи, обследования, болезнь).
"""

import re

# Мотивы: ключ -> (regex, сколько последних постов смотреть, сколько раз мотив можно встретить в них,
#                 человеческое описание для запрета в промпте)
MOTIFS = {
    "history": (
        r"версал|людовик|корол[ья]-солнц|екатерин|при двор|придворн|\bрим[аеу]?\b|римск|"
        r"патрици|гладиатор|колизе|пале-рояль|фаворитк|куртизан|"
        r"девятнадцат\w* век|восемнадцат\w* век|xix век|xviii век",
        4, 0, "исторические параллели и придворные образы (Версаль, двор, Рим, фавориты, девятнадцатый век)",
    ),
    "credo_teen": (r"вечн\w* подрост", 8, 0, "«зритель - вечный подросток»"),
    "credo_fridge": (r"холодильник", 8, 0, "«уходит к холодильнику»"),
    "credo_fake": (r"не прощает фальш|бедност\w* картинки|чует фальш|считывает фальш", 8, 0, "«аудитория прощает бедность картинки, но не фальшь»"),
    "hat": (r"снимаю шляпу", 8, 0, "«снимаю шляпу»"),
    "razvodka": (r"разводк", 5, 1, "слово «разводка»"),
    "prime": (r"\bпрайм", 4, 1, "слово «прайм» и «доля в прайме»"),
    "jargon_tv": (r"перебивк|аппаратн|хронометраж|летучк", 3, 1, "ТВ-жаргон «перебивка», «аппаратная», «хронометраж», «летучка»"),
    "polish": (r"вылизан|вылизыва|стерильн|пластмасс|пластиков", 4, 1, "«вылизанный», «стерильный», «пластмассовый»"),
    "nerve": (r"\bнерв[аеу]?\b|\bнервом\b", 4, 1, "слово «нерв»"),
    "packaging": (r"упаковк|упаковыва|упакова", 4, 1, "слово «упаковка»"),
    "nostalgia": (r"в девяност|в нулев|в конце девяност|малинов\w* пиджак", 3, 0, "воспоминания «в девяностые / в нулевые мы...»"),
    "window_weather": (r"у окна|за окном|хмар|пасмурн|слякот|морос|плюс \w+(?:надцат|дцат)\w*", 3, 0, "погода, «у окна», «за окном»"),
    "coffee": (r"\bтурк[аеиу]|\bварю\b|\bварил\b|свой кофе|мой кофе|утренн\w* кофе", 4, 0, "свой кофе и турка"),
    "smb_triad": (r"салон|юрфирм|юрбюро|стройк|продакшен", 2, 1, "примеры «салон красоты, юрфирма, стройка, продакшен» в выводе"),
    "takeaway_if": (r"(?m)^\s*(?:Если вы|Если у вас|Если ваш)", 2, 0, "вывод, который начинается с «Если вы / Если у вас»"),
    "takeaway_stop": (r"(?m)^\s*(?:Перестаньте|Хватит|Прекратите|Бросьте)", 2, 0, "вывод, который начинается с «Перестаньте / Хватит»"),
    # лимит -1: запрещено всегда, без оглядки на историю
    "emotion_label": (r"\bиспытыва\w+|\bчувствую\b|накрыва\w+|почти физическ|меня знобит", 1, -1, "названные вслух эмоции («испытываю брезгливость», «чувствую тоску»)"),
    "bet_phrase": (r"делаю ставку|моя ставка", 4, 1, "«делаю ставку / моя ставка»"),
}
_COMPILED = {k: re.compile(v[0], re.IGNORECASE) for k, v in MOTIFS.items()}

# Всегда запрещено в публичном канале (правило Алекса, 25.10.2026)
PRIVATE_RE = re.compile(
    # «маме», «маму», «у мамы»: так он говорил о своей матери; «мама блогерши» из новости не трогаем
    r"\bмаме\b|\bмаму\b|\bмамой\b|\bу мамы\b|\bмамин|"
    r"\b(?:мо[яейюи]|мою|моего|моему|моим|моих|сво[яеию]|свою|своего|своих)\s+(?:бывш\w+\s+)?"
    r"(?:мам|мат[ьеи]|отц|отец|жен|супруг|доч|сын|внук|внучк|дед|бабушк|семь|родн|подруг)\w*|"
    r"таблетк|ремисси|онколог|обследован|химиотерап|облучени|щитовидк|\bрак\b|\bрака\b|\bраком\b",
    re.IGNORECASE,
)
PRIVATE_FIX = (
    "личное, которого он никогда не пишет в публичном канале: семья (мама, жёны, дети, внуки, дед) и здоровье "
    "(болезнь, таблетки, врачи, обследования). Убери это совсем, не намекай"
)

# Начало поста с того, что автор делает или видит (читаю, смотрю, стою у окна, варю кофе)
SELF_OPENING_RE = re.compile(
    r"^\s*(?:я\s+)?(?:читаю|смотрю|наблюдаю|стою|сижу|досмотрел|досматриваю|варю|варил|еду|листаю|перечитываю|"
    r"пересматриваю|собираюсь|жду|за окном|у окна)\b",
    re.IGNORECASE,
)
SELF_OPENING_FIX = "пост начинается с того, что ты делаешь или видишь («читаю», «смотрю», «стою у окна»): начни прямо с мысли о новости"

# Стили вывода для читателя: чередуются, чтобы концовки не были одной формулой
TAKEAWAY_STYLES = [
    ("action", "одно конкретное действие, которое читатель может сделать завтра, без вступления «Если вы...»"),
    ("rule", "короткое правило в одну фразу, которое хочется переписать себе"),
    ("question", "вопрос, который читатель должен задать себе о своём деле, и одна подсказка, как на него ответить"),
    ("myplace", "«На вашем месте я бы...» с одним конкретным ходом"),
    ("woven", "вывод вплетён в последнюю мысль поста, без отдельного абзаца-совета"),
    ("punch", "колкая финальная фраза, а за ней одна короткая практическая подсказка"),
]


def _texts(history: list[dict], n: int) -> list[str]:
    return [h.get("text") or "" for h in history[-n:]]


def usage(history: list[dict]) -> dict[str, int]:
    """Сколько из последних постов (по окну мотива) содержат каждый мотив."""
    return {k: sum(1 for t in _texts(history, MOTIFS[k][1]) if _COMPILED[k].search(t)) for k in MOTIFS}


def banned_motifs(history: list[dict]) -> list[str]:
    """Мотивы, которые в следующем посте запрещены: в окне последних постов их уже было больше лимита."""
    used = usage(history)
    return [k for k in MOTIFS if used[k] > MOTIFS[k][2]]


ALWAYS = [k for k in MOTIFS if MOTIFS[k][2] < 0]  # запрещено всегда, в промпте это отдельные правила


def prompt_block(banned: list[str]) -> str:
    banned = [k for k in banned if k not in ALWAYS]
    if not banned:
        return ""
    items = "\n".join(f"- {MOTIFS[k][3]}" for k in banned)
    return (
        "[НЕ ПОВТОРЯЙСЯ: это было в твоих недавних постах, в этом посте этого нет совсем]\n" + items
    )


def motifs_in(text: str) -> list[str]:
    """Мотивы, которые уже есть в тексте (для добивки: не повторять слова своего же поста)."""
    return [k for k in MOTIFS if MOTIFS[k][2] >= 0 and _COMPILED[k].search(text or "")]


def has_private(text: str) -> bool:
    return bool(PRIVATE_RE.search(text or ""))


def violations(text: str, banned: list[str]) -> list[str]:
    """Проблемы для переписывания: запрещённые сейчас мотивы и всегда запрещённое личное."""
    keys = list(dict.fromkeys(list(banned) + ALWAYS))
    problems = [(f"{MOTIFS[k][3]}: убери" if k in ALWAYS else f"повтор из недавних постов: {MOTIFS[k][3]}, убери или скажи иначе")
                for k in keys if _COMPILED[k].search(text or "")]
    if has_private(text):
        problems.append(PRIVATE_FIX)
    first = re.split(r"(?<=[.!?…])\s", (text or "").strip(), maxsplit=1)[0]
    if SELF_OPENING_RE.search(first):
        problems.append(SELF_OPENING_FIX)
    return problems


def pick_takeaway_style(history: list[dict], rng) -> tuple[str, str]:
    recent = {h.get("takeaway_style") for h in history[-2:]}
    pool = [s for s in TAKEAWAY_STYLES if s[0] not in recent] or TAKEAWAY_STYLES
    return rng.choice(pool)
