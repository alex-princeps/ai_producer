    @classmethod
    def get_current_context(cls) -> str:
        """
        Возвращает текстовое описание того, где Аристарх сейчас и что делает.
        [NEW] Кэширует результат на 1 час для поддержания реалистичности диалога.
        """
        # Устанавливаем московское время
        moscow_tz = pytz.timezone('Europe/Moscow')
        now = datetime.now(moscow_tz)
        current_hour = now.hour
        current_date = now.date()
        
        # Если контекст уже сгенерирован для этого часа — отдаем его из кэша
        if cls._cached_context and cls._cached_date == current_date and cls._cached_hour == current_hour:
            return cls._cached_context

        weekday = now.weekday()  # 0 - ПН, 6 - ВСКР

        # Выбор сценария
        if 0 <= current_hour < 8:
            options = cls.NIGHT_CONTEXTS
        elif weekday >= 5:  # Суббота (5) и Воскресенье (6)
            options = cls.WEEKEND_SCHEDULE.get(current_hour, ["Сидит в офисе на выходных. Злится."])
        else:
            options = cls.WEEKDAY_SCHEDULE.get(current_hour, ["Сидит в офисе. Работает."])
        
        # Сохраняем в кэш
        cls._cached_context = random.choice(options)
        cls._cached_date = current_date
        cls._cached_hour = current_hour
        
        return cls._cached_context