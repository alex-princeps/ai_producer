def infer_register_from_text(text: str) -> RegisterType:
    """Быстрый детерминированный классификатор регистра по тексту брифа/запроса (фоллбэк и первичная разметка папки)."""
    t = (text or "").lower()
    if re.search(r"(pr\b|пиар|пресс-релиз|антикризис|репутац|журналист|глянец|blueprint|vogue|tatler|бренд-медиа.*pr)", t):
        return "PR_BRAND"
    if re.search(
        r"(психолог|гештальт|коуч|блогер|лайфстайл|прогрев|сторителлинг|рилс|reels|кружоч|пилатес|фитнес|"
        r"нутрициолог|стилист|бьюти|косметик|онлайн-запуск|онлайн-школ|эзотерик|энергопрактик|вибрац|маникюр|барбершоп|smm)",
        t,
    ):
        return "CREATOR_MEDIA"
    return "HARD_B2B"


